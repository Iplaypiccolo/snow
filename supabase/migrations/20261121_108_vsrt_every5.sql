-- 108. 초단기 수집 확인을 10분마다(8·18·28…분) → 5분마다(3·8·13…분). 2026-11-21 Claude Code, 사용자 "적용해".
--  * 까닭: 발표 8분 뒤에는 기상청에 그 발표가 아직 없어(11/21 18시 18:10→18:28, 18:20→18:38, 18:30→18:48 받음) 화면이 늘 발표 18~28분 뒤 값.
--    날씨누리는 약 13분 뒤부터 새 발표. 13분 뒤에도 시도하고, 2분 제한에 걸린 수집(11/21 09:28)도 5분 뒤 이어서.
--  * kick_vsrt 는 그대로: 이번 10분 발표를 이미 다 받았으면 부르지 않음, 3분 안에 다시 부르지 않음.
--  * 늘어나는 기상청 호출: '아직 없음' 확인 1번씩(하루 약 +150번).
select cron.schedule('collect-vsrt', '3-58/5 * * * *', $c$select private.kick_vsrt()$c$);
